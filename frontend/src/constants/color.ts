export const backgroundColorArray = Object.keys(colorPalette).map((color) => {
  return {
    name: color,
    value: colourNameToHex(color),
  }
});

let keepSameData: Array<string> = [];
export const borderColorArray = Object.values(colorPalette)
  .filter((color) => {
    const hex: string = colourNameToHex(color);
    const isExisting = keepSameData.includes(hex)
    
    if (!isExisting) {
      keepSameData.push(hex);
    }
    return !isExisting;
  })
  .map((color) => ({
    name: color,
    value: colourNameToHex(color),
  }));